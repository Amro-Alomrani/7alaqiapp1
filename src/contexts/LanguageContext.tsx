interface LanguageContextType {
  language: Language;
  setLanguage: (l: Language) => void;
  toggleLanguage: () => void;
  t: Omit<typeof translations['en'], 'dir'> & { dir: 'ltr' | 'rtl' };
  isRTL: boolean;
}

const LanguageContext = createContext<LanguageContextType>({
  language: 'en',
  setLanguage: () => {},
  toggleLanguage: () => {},
  t: translations.en,
  isRTL: false,
});

export function LanguageProvider({ children }: { children: React.ReactNode }) {
  const [language, setLanguageState] = useState<Language>(() => {
    const saved = (localStorage.getItem('halaqi-lang') || localStorage.getItem('barberco-lang')) as Language | null;
    if (saved === 'ar' || saved === 'en') return saved;
    return 'ar';
  });

  const setLanguage = (l: Language) => {
    setLanguageState(l);
    localStorage.setItem('halaqi-lang', l);
  };

  const toggleLanguage = () => setLanguage(language === 'en' ? 'ar' : 'en');

  useEffect(() => {
    const dir = translations[language].dir;
    document.documentElement.setAttribute('dir', dir);
    document.documentElement.setAttribute('lang', language);
    document.body.setAttribute('dir', dir);
  }, [language]);

  return (
    <LanguageContext.Provider value={{
      language,
      setLanguage,
      toggleLanguage,
      t: translations[language],
      isRTL: translations[language].dir === 'rtl',
    }}>
      <div dir={translations[language].dir} className="contents">
        {children}
      </div>
    </LanguageContext.Provider>
  );
}

export const useLanguage = () => useContext(LanguageContext);
